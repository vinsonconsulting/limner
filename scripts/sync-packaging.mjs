#!/usr/bin/env node
// Packaging single-source sync (review r2). Companion to sync-version.mjs.
//
// Three generated sites keep the published artifacts self-contained:
//
//   1. packages/limner-core/src/schema.generated.ts — the D1/SQLite initial
//      schema embedded as a TS constant. The stdio entry point defaults to
//      this (migrations/ lives outside the .mcpb pack root and the npm
//      `files:` set, so a path-based default ENOENTs on every end-user
//      install).
//   2. packages/limner-mcp/{LICENSE,NOTICE} — committed copies of the root
//      license files so the .mcpb / npm artifact redistributes the required
//      Apache-2.0 §4 texts.
//   3. packages/limner-core/src/fonts.generated.ts — the bundled renderText
//      fonts embedded as base64 so compose resolves them server-side by id
//      (the MCP tool no longer transits font bytes inline; a large base64
//      font truncates on the wire). Embedding keeps the bytes in both the
//      Workers bundle and the .mcpb without a filesystem read.
//
// Run via `pnpm sync-packaging` (root `build` runs it next to sync-version);
// CI regenerates both and fails on drift (see .github/workflows/ci.yml).

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const abs = (rel) => join(repoRoot, rel);

let changed = 0;
function write(rel, next) {
  const path = abs(rel);
  let current = '';
  try {
    current = readFileSync(path, 'utf8');
  } catch {
    /* file does not exist yet */
  }
  if (current !== next) {
    writeFileSync(path, next);
    changed++;
    console.log(`  synced ${rel}`);
  }
}

// 1. Embedded schema. Escape order matters: backslashes first, then
//    backticks and ${ (template-literal metacharacters).
const schemaSql = readFileSync(abs('migrations/0001_initial_schema.sql'), 'utf8');
const escaped = schemaSql
  .replace(/\\/g, '\\\\')
  .replace(/`/g, '\\`')
  .replace(/\$\{/g, '\\${');
const schemaTs =
  '// GENERATED by scripts/sync-packaging.mjs — do not edit by hand.\n' +
  '// Source of truth: migrations/0001_initial_schema.sql. Run\n' +
  '// `pnpm sync-packaging` after editing the migration.\n' +
  `export const INITIAL_SCHEMA_SQL = \`${escaped}\` as const;\n`;
write('packages/limner-core/src/schema.generated.ts', schemaTs);

// 2. License texts shipped with the bundle/package.
write('packages/limner-mcp/LICENSE', readFileSync(abs('LICENSE'), 'utf8'));
write('packages/limner-mcp/NOTICE', readFileSync(abs('NOTICE'), 'utf8'));

// 3. Built-in renderText fonts embedded as base64. base64 is [A-Za-z0-9+/=]
//    only, so a single-quoted literal needs no escaping.
const fontB64 = readFileSync(
  abs('packages/limner-core/assets/fonts/IBMPlexSans-Regular.ttf'),
).toString('base64');
const fontsTs =
  '// GENERATED by scripts/sync-packaging.mjs — do not edit by hand.\n' +
  '// Source of truth: packages/limner-core/assets/fonts/*.ttf. Run\n' +
  '// `pnpm sync-packaging` after adding or replacing a bundled font.\n' +
  `export const IBM_PLEX_SANS_REGULAR_B64 = '${fontB64}' as const;\n`;
write('packages/limner-core/src/fonts.generated.ts', fontsTs);

console.log(
  changed === 0
    ? 'packaging files already in sync'
    : `packaging sync complete (${changed} file(s) updated)`,
);
